import { spawnSync } from 'child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join, resolve } from 'path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

/**
 * Exercises `scripts/verify-migrations.sh` against throwaway migration trees.
 * Schema validation and the database tier are disabled here so the suite runs
 * without Prisma engines or Postgres; they are covered by the CI job itself.
 */
const SCRIPT = resolve(__dirname, '..', '..', 'scripts', 'verify-migrations.sh');
const hasBash = spawnSync('bash', ['--version']).status === 0;

const SCHEMA = `datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

model Thing {
  id String @id
}
`;

const LOCK = '# Please do not edit this file manually\nprovider = "postgresql"\n';

describe.skipIf(!hasBash)('scripts/verify-migrations.sh', () => {
  let root: string;
  let migrationsDir: string;

  const write = (relativePath: string, content: string) => {
    const path = join(migrationsDir, relativePath);
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, content);
  };

  const git = (...args: string[]) => {
    const result = spawnSync('git', args, { cwd: root, encoding: 'utf8' });
    if (result.status !== 0) {
      throw new Error(`git ${args.join(' ')} failed: ${result.stderr}`);
    }
  };

  const run = (env: Record<string, string> = {}) => {
    const result = spawnSync('bash', [SCRIPT], {
      cwd: root,
      encoding: 'utf8',
      env: {
        ...process.env,
        GITHUB_ACTIONS: '',
        SHADOW_DATABASE_URL: '',
        MIGRATION_BASE_REF: '',
        SKIP_SCHEMA_VALIDATION: 'true',
        MIGRATIONS_DIR: 'prisma/migrations',
        SCHEMA_PATH: 'prisma/schema.prisma',
        ...env,
      },
    });
    return { status: result.status, output: `${result.stdout}${result.stderr}` };
  };

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'astroid-migrations-'));
    migrationsDir = join(root, 'prisma', 'migrations');
    mkdirSync(migrationsDir, { recursive: true });
    writeFileSync(join(root, 'prisma', 'schema.prisma'), SCHEMA);
    write('migration_lock.toml', LOCK);
    write(
      '0_init/migration.sql',
      'CREATE TABLE "Thing" ("id" TEXT NOT NULL, PRIMARY KEY ("id"));\n',
    );
    write('20260101000000_add_name/migration.sql', 'ALTER TABLE "Thing" ADD COLUMN "name" TEXT;\n');
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
  });

  it('passes a well-formed migration history', () => {
    const { status, output } = run();

    expect(output).toContain('Inspected 2 migration folder(s).');
    expect(output).toContain('Migration verification passed');
    expect(status).toBe(0);
  });

  it('accepts comments, strings and dollar-quoted bodies containing SQL punctuation', () => {
    write(
      '20260102000000_trigger/migration.sql',
      [
        '-- a comment with an unbalanced ( and a ;',
        '/* block comment ) ; */',
        `INSERT INTO "Thing" ("id") VALUES ('it''s (fine);');`,
        'CREATE FUNCTION touch() RETURNS trigger AS $body$',
        "BEGIN NEW.name := '('; RETURN NEW; END;",
        '$body$ LANGUAGE plpgsql;',
        '',
      ].join('\r\n'),
    );

    expect(run().status).toBe(0);
  });

  it('fails with an actionable message when a folder lacks migration.sql', () => {
    mkdirSync(join(migrationsDir, '20260102000000_forgotten'));

    const { status, output } = run();

    expect(status).toBe(1);
    expect(output).toContain('20260102000000_forgotten: Missing migration.sql');
  });

  it.each([
    ['an empty file', '', 'contains no SQL statements'],
    ['only comments', '-- TODO\n/* nothing */\n', 'contains no SQL statements'],
    [
      'an unterminated final statement',
      'ALTER TABLE "Thing" ADD COLUMN "x" TEXT\n',
      ':1: Invalid SQL: final statement is not terminated',
    ],
    [
      'an unclosed parenthesis',
      'CREATE TABLE "T" (\n  "id" TEXT;\n',
      ':2: Invalid SQL: statement ends with 1 unclosed "("',
    ],
    ['a stray closing parenthesis', 'SELECT 1);\n', ':1: Invalid SQL: unbalanced ")"'],
    [
      'an unterminated string',
      'INSERT INTO "T" VALUES (\'oops);\n',
      'unterminated string literal (opened on line 1)',
    ],
    ['an unterminated block comment', 'SELECT 1;\n/* never closed\n', 'unterminated /* comment'],
    [
      'a merge-conflict marker',
      'SELECT 1;\n<<<<<<< HEAD\nSELECT 2;\n',
      ':2: Invalid SQL: unresolved merge-conflict marker',
    ],
  ])('rejects a migration.sql with %s', (_label, sql, expected) => {
    write('20260102000000_broken/migration.sql', sql);

    const { status, output } = run();

    expect(status).toBe(1);
    expect(output).toContain('20260102000000_broken/migration.sql');
    expect(output).toContain(expected);
  });

  it('rejects malformed folder names and duplicate timestamps', () => {
    write('add_thing/migration.sql', 'SELECT 1;\n');
    write('20260101000000_clash/migration.sql', 'SELECT 1;\n');

    const { status, output } = run();

    expect(status).toBe(1);
    expect(output).toContain("Invalid migration folder name 'add_thing'");
    expect(output).toContain('Timestamp 20260101000000 is shared with');
  });

  it('rejects a missing lock file and a provider mismatch', () => {
    rmSync(join(migrationsDir, 'migration_lock.toml'));
    expect(run().output).toContain('migration_lock.toml is missing');

    write('migration_lock.toml', 'provider = "mysql"\n');
    const { status, output } = run();
    expect(status).toBe(1);
    expect(output).toContain(
      'provider "mysql" does not match the schema datasource provider "postgresql"',
    );
  });

  it('rejects stray files at the top of the migrations directory', () => {
    write('fix.sql', 'SELECT 1;\n');

    const { status, output } = run();

    expect(status).toBe(1);
    expect(output).toContain('fix.sql: Unexpected file in migrations directory');
  });

  it('reports every error in one run and emits GitHub annotations in CI', () => {
    mkdirSync(join(migrationsDir, '20260102000000_forgotten'));
    write('20260103000000_broken/migration.sql', 'SELECT (1;\n');

    const { status, output } = run({ GITHUB_ACTIONS: 'true' });

    expect(status).toBe(1);
    expect(output).toContain(
      '::error file=prisma/migrations/20260102000000_forgotten::Missing migration.sql',
    );
    expect(output).toContain(
      '::error file=prisma/migrations/20260103000000_broken/migration.sql,line=1::Invalid SQL',
    );
    expect(output).toContain('FAILED: 2 error(s)');
  });

  it('rejects leftover merge artefacts and conflict markers in a migration folder', () => {
    write('20260201000000_conflicted/migration.sql', 'SELECT 1;\n');
    write('20260201000000_conflicted/migration.sql.orig', 'SELECT 1;\n');
    write('20260201000000_conflicted/notes.sql', '<<<<<<< HEAD\nSELECT 2;\n');

    const { status, output } = run();

    expect(status).toBe(1);
    expect(output).toContain("Leftover merge artefact 'migration.sql.orig' in migration folder");
    expect(output).toContain("Unresolved merge-conflict marker in 'notes.sql'");
  });

  describe('statement classification', () => {
    it('rejects forbidden statements', () => {
      write(
        '20260201000000_forbidden/migration.sql',
        [
          'DROP DATABASE "astroid";',
          'DROP SCHEMA public CASCADE;',
          'CREATE ROLE reporting;',
          'GRANT ALL ON SCHEMA public TO reporting;',
          "ALTER SYSTEM SET work_mem = '1GB';",
        ].join('\n'),
      );

      const { status, output } = run();

      expect(status).toBe(1);
      expect(output).toContain('Forbidden statement: DROP DATABASE "astroid"');
      expect(output).toContain('Forbidden statement: DROP SCHEMA public CASCADE');
      expect(output).toContain('Forbidden statement: CREATE ROLE reporting');
      expect(output).toContain('Forbidden statement: GRANT ALL ON SCHEMA public TO reporting');
      expect(output).toContain("Forbidden statement: ALTER SYSTEM SET work_mem = '1GB'");
    });

    it('rejects a destructive statement that does not opt in', () => {
      write(
        '20260201000000_cleanup/migration.sql',
        '-- DROP TABLE "Thing"; in a comment is ignored\nALTER TABLE "Thing" DROP COLUMN "name";\n',
      );

      const { status, output } = run();

      expect(status).toBe(1);
      expect(output).toContain(
        'ERROR: prisma/migrations/20260201000000_cleanup/migration.sql:2: Destructive statement is not allowed',
      );
      expect(output).not.toContain('migration.sql:1: Destructive statement');
    });

    it('accepts a destructive statement that opts in explicitly', () => {
      write(
        '20260201000000_cleanup/migration.sql',
        '-- astroid:allow-destructive the column is unused and holds no data\nALTER TABLE "Thing" DROP COLUMN "name";\n',
      );

      const { status, output } = run();

      expect(status).toBe(0);
      expect(output).toContain(
        'WARNING: prisma/migrations/20260201000000_cleanup/migration.sql:2: Destructive statement: ALTER TABLE "Thing" DROP COLUMN "name"',
      );
      expect(output).toContain('passed with 1 warning(s)');
    });

    it('accepts every destructive statement when ALLOW_DESTRUCTIVE_MIGRATIONS is set', () => {
      write('20260201000000_cleanup/migration.sql', 'TRUNCATE TABLE "Thing";\n');

      const { status, output } = run({ ALLOW_DESTRUCTIVE_MIGRATIONS: 'true' });

      expect(status).toBe(0);
      expect(output).toContain(
        'WARNING: prisma/migrations/20260201000000_cleanup/migration.sql:1: Destructive statement',
      );
      expect(output).toContain('passed with 1 warning(s)');
    });

    it('rejects a NOT NULL column without DEFAULT on a table that already holds rows', () => {
      write(
        '20260201000000_not_null/migration.sql',
        '  ALTER TABLE "Thing" ADD COLUMN "label" TEXT NOT NULL;\n',
      );

      const { status, output } = run();

      expect(status).toBe(1);
      expect(output).toContain(
        'ERROR: prisma/migrations/20260201000000_not_null/migration.sql:1: Unsafe statement: ADD COLUMN ... NOT NULL without DEFAULT on table "Thing"',
      );
    });

    it('allows a NOT NULL column on a table created by the same migration', () => {
      write(
        '20260201000000_not_null/migration.sql',
        'CREATE TABLE "Widget" ("id" TEXT NOT NULL, PRIMARY KEY ("id"));\nALTER TABLE "Widget" ADD COLUMN "label" TEXT NOT NULL;\n',
      );

      expect(run().status).toBe(0);
    });

    it('allows a NOT NULL column that has a DEFAULT', () => {
      write(
        '20260201000000_not_null/migration.sql',
        'ALTER TABLE "Thing" ADD COLUMN "label" TEXT NOT NULL DEFAULT \'\';\n',
      );

      expect(run().status).toBe(0);
    });

    it('rejects CREATE INDEX CONCURRENTLY with IF NOT EXISTS', () => {
      write(
        '20260201000000_index/migration.sql',
        'CREATE INDEX CONCURRENTLY IF NOT EXISTS "Thing_label_idx" ON "Thing" ("label");\n',
      );

      const { status, output } = run();

      expect(status).toBe(1);
      expect(output).toContain(
        'Unsafe statement: CREATE INDEX CONCURRENTLY ... IF NOT EXISTS is not allowed',
      );
    });

    it('rejects CREATE INDEX CONCURRENTLY next to another statement', () => {
      write(
        '20260201000000_index/migration.sql',
        'CREATE INDEX CONCURRENTLY "Thing_label_idx" ON "Thing" ("label");\nCREATE INDEX "Thing_id_idx" ON "Thing" ("id");\n',
      );

      const { status, output } = run();

      expect(status).toBe(1);
      expect(output).toContain(
        'Unsafe statement: CREATE INDEX CONCURRENTLY must be the only statement in a migration',
      );
    });

    it('accepts a single CREATE INDEX CONCURRENTLY statement', () => {
      write(
        '20260201000000_index/migration.sql',
        'CREATE INDEX CONCURRENTLY "Thing_label_idx" ON "Thing" ("label");\n',
      );

      expect(run().status).toBe(0);
    });
  });

  describe('history checks against MIGRATION_BASE_REF', () => {
    beforeEach(() => {
      git('init', '-q');
      git('config', 'user.email', 'test@example.com');
      git('config', 'user.name', 'test');
      git('config', 'core.autocrlf', 'false');
      git('add', '.');
      git('commit', '-q', '-m', 'base');
      git('tag', 'base');
    });

    it('passes when a new migration is appended', () => {
      write(
        '20260201000000_add_email/migration.sql',
        'ALTER TABLE "Thing" ADD COLUMN "email" TEXT;\n',
      );

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(output).toContain('New migration: 20260201000000_add_email');
      expect(status).toBe(0);
    });

    it('rejects edits to a migration that already exists on the base ref', () => {
      write(
        '20260101000000_add_name/migration.sql',
        'ALTER TABLE "Thing" ADD COLUMN "title" TEXT;\n',
      );

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(1);
      expect(output).toContain(
        "Migration '20260101000000_add_name' already exists on base and was modified",
      );
    });

    it('rejects deleting a migration that exists on the base ref', () => {
      rmSync(join(migrationsDir, '20260101000000_add_name'), { recursive: true });

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(1);
      expect(output).toContain(
        "Migration '20260101000000_add_name' exists on base but was deleted",
      );
    });

    it('rejects a new migration that would be applied out of order', () => {
      write('20251231000000_backdated/migration.sql', 'SELECT 1;\n');

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(1);
      expect(output).toContain(
        "New migration '20251231000000_backdated' sorts before '20260101000000_add_name'",
      );
    });

    it('warns about an index created without CONCURRENTLY in a new migration', () => {
      write(
        '20260201000000_index/migration.sql',
        'CREATE INDEX "Thing_name_idx" ON "Thing" ("name");\n',
      );

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(0);
      expect(output).toContain(
        'WARNING: prisma/migrations/20260201000000_index/migration.sql:1: Index created without CONCURRENTLY',
      );
      expect(output).toContain('passed with 1 warning(s)');
    });

    it('rejects a destructive statement in a new migration', () => {
      write(
        '20260201000000_cleanup/migration.sql',
        '-- DROP TABLE "Thing"; in a comment is ignored\nALTER TABLE "Thing" DROP COLUMN "name";\n',
      );

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(1);
      expect(output).toContain(
        'ERROR: prisma/migrations/20260201000000_cleanup/migration.sql:2: Destructive statement is not allowed',
      );
      expect(output).not.toContain('migration.sql:1: Destructive statement');
    });

    it('accepts a destructive statement in a new migration that opts in', () => {
      write(
        '20260201000000_cleanup/migration.sql',
        '-- astroid:allow-destructive the column is unused and holds no data\nALTER TABLE "Thing" DROP COLUMN "name";\n',
      );

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(0);
      expect(output).toContain(
        'WARNING: prisma/migrations/20260201000000_cleanup/migration.sql:2: Destructive statement: ALTER TABLE "Thing" DROP COLUMN "name"',
      );
      expect(output).toContain('passed with 1 warning(s)');
    });

    it('only warns about a destructive statement in an already merged migration', () => {
      write(
        '20260101000000_add_name/migration.sql',
        'ALTER TABLE "Thing" ADD COLUMN "name" TEXT;\nDROP INDEX "Thing_name_idx";\n',
      );

      const { status, output } = run({ MIGRATION_BASE_REF: 'base' });

      expect(status).toBe(1);
      expect(output).toContain(
        "Migration '20260101000000_add_name' already exists on base and was modified",
      );
      expect(output).toContain(
        'WARNING: prisma/migrations/20260101000000_add_name/migration.sql:2: Destructive statement in an already merged migration',
      );
    });

    it('skips with a warning when the base ref cannot be resolved', () => {
      const { status, output } = run({ MIGRATION_BASE_REF: 'origin/does-not-exist' });

      expect(status).toBe(0);
      expect(output).toContain("cannot resolve a merge base with 'origin/does-not-exist'");
    });
  });
});
